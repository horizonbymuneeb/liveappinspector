#!/usr/bin/env python3
"""Generate schema/report-v1.schema.json from a real acquisition report.

Type inference is structural: object/array shapes are merged across elements so a
single rich capture describes the whole model. Empty collections cannot reveal
their item shape, so they are emitted as `{}` with a note - that is intentional,
because guessing would be worse than admitting the gap.

Usage:
    lai inspect --pid <pid> --json /tmp/sample.json
    python scripts/gen-schema.py /tmp/sample.json schema/report-v1.schema.json
"""
import json
import sys

SCHEMA_ID = "https://github.com/horizonbymuneeb/liveappinspector/schema/report-v1.schema.json"
DESCRIPTION = (
    "Structural schema for a sealed acquisition report. Field semantics, provenance "
    "and caveats are documented in docs/SCHEMA.md and docs/FORENSIC_NOTES.md. Every "
    "section carries a `meta` block with status/error/warnings plus a UTC "
    "`collected_at_utc`. Generated by scripts/gen-schema.py from a real acquisition."
)


def merge(a, b):
    if a == b:
        return a
    ta, tb = a.get("type"), b.get("type")
    if ta == tb == "object":
        props = dict(a.get("properties", {}))
        for k, sc in b.get("properties", {}).items():
            props[k] = merge(props[k], sc) if k in props else sc
        return {"type": "object", "properties": props}
    if ta and tb and ta != tb:
        ta = ta if isinstance(ta, list) else [ta]
        tb = tb if isinstance(tb, list) else [tb]
        return {"type": sorted(set(ta) | set(tb))}
    return a


def infer(value):
    if value is None:
        return {"type": ["null", "string"]}
    if isinstance(value, bool):
        return {"type": "boolean"}
    if isinstance(value, int):
        return {"type": "integer"}
    if isinstance(value, float):
        return {"type": "number"}
    if isinstance(value, str):
        return {"type": "string"}
    if isinstance(value, list):
        if not value:
            return {"type": "array", "items": {},
                    "description": "empty at capture time - item shape not inferable"}
        subs = [infer(v) for v in value]
        if all(isinstance(v, dict) for v in value):
            props = {}
            for s in subs:
                for k, sc in s.get("properties", {}).items():
                    props[k] = merge(props[k], sc) if k in props else sc
            required = sorted(set.intersection(*[set(s.get("required", [])) for s in subs]))
            items = {"type": "object", "properties": props}
            if required:
                items["required"] = required
            return {"type": "array", "items": items}
        if all(isinstance(v, str) for v in value):
            return {"type": "array", "items": {"type": "string"}}
        return {"type": "array", "items": subs[0]}
    if isinstance(value, dict):
        props = {k: infer(v) for k, v in value.items()}
        return {"type": "object", "properties": props, "required": sorted(props.keys())}
    return {}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    with open(sys.argv[1], encoding="utf-8-sig") as fh:
        report = json.load(fh)
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        "title": "LiveAppInspector forensic report (liveappinspector.report/v1)",
        "description": DESCRIPTION,
        "type": "object",
        "additionalProperties": True,
    }
    inferred = infer(report)
    for key in ("properties", "required"):
        if key in inferred:
            schema[key] = inferred[key]
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as fh:
        json.dump(schema, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    print(f"wrote {sys.argv[2]} ({len(schema.get('properties', {}))} sections)")


if __name__ == "__main__":
    main()
